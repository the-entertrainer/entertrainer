import assert from 'node:assert/strict';
import {segmentDistance,nextCombo} from '../games/fever/combat.js';
assert.equal(segmentDistance(0,0,-2,0,2,0),0,'Fast sweep crosses a target between events');
assert.equal(segmentDistance(0,1,-2,0,2,0),1,'Off-path targets are not hit');
assert.equal(segmentDistance(4,0,-2,0,2,0),2,'Do not extend swipe beyond endpoint');
assert.equal(segmentDistance(1,0,0,0,0,0),1,'Stationary pointer has a finite distance');
assert.equal(nextCombo(3,100,1000),4);
assert.equal(nextCombo(3,100,2000),1,'Expired chains reset');
assert.equal(nextCombo(8,100,200),8,'Combos are bounded');
console.log('PASS: swipe tunnelling, endpoints, stationary input, combo expiry and cap');
